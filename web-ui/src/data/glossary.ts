// 文案口径与后端实现对齐：
// - WF 切窗语义见 src/easy_tdx/backtest/walkforward.py（预热区 30%、每窗独立开仓）；
// - 综合评分权重见 scoring.py（收益 50/夏普 15/回撤 10/索提诺 5/WF 20）；
// - 适配性体检 8 项见 fitness.py（train/valid/test = 60/20/20，≥75% 高适配）；
// - 指标阈值参考 grading.py THRESHOLDS 的经验锚点。
//
// 排版约定：文案中的 **文字** 由 GlossaryList 渲染为粗体重点（阈值/口诀），
// 其余为细体次要文字；formula 用等宽字体单独一行展示。

export interface GlossaryEntry {
  /** 词条名（面板上出现的原词） */
  term: string
  /** 一句话定义：这是什么 / 怎么算。支持 **粗体** 标重点 */
  summary: string
  /** 计算公式（等宽字体展示），可选 */
  formula?: string
  /** 补充细节：怎么来的、口径说明（细体）。支持 **粗体** */
  detail?: string
  /** 如何看 / 如何用：阈值与经验法则（"怎么看"标签行）。支持 **粗体** */
  guide?: string
}

export interface GlossarySection {
  /** 分组标题（如 收益类 / 风险类） */
  title: string
  entries: GlossaryEntry[]
}

